import heapq

# Base de conocimiento (Reglas lógicas del sistema de transporte)
sistema_transporte = {
    'A': {'B': 5, 'C': 8},
    'B': {'A': 5, 'D': 6, 'E': 9},
    'C': {'A': 8, 'D': 4},
    'D': {'B': 6, 'C': 4, 'F': 5},
    'E': {'B': 9, 'F': 3},
    'F': {'D': 5, 'E': 3}
}

# Heurística (Estimación en línea recta hacia el destino F)
heuristica = {
    'A': 10, 'B': 7, 'C': 6, 'D': 4, 'E': 2, 'F': 0
}

def buscar_mejor_ruta(inicio, destino, grafo, heuristica):
    rutas_por_evaluar = []
    heapq.heappush(rutas_por_evaluar, (0, inicio))
    costo_real = {inicio: 0}
    ruta_previa = {inicio: None}

    while rutas_por_evaluar:
        _, estacion_actual = heapq.heappop(rutas_por_evaluar)

        if estacion_actual == destino:
            ruta_final = []
            while estacion_actual is not None:
                ruta_final.append(estacion_actual)
                estacion_actual = ruta_previa[estacion_actual]
            ruta_final.reverse()
            return ruta_final, costo_real[destino]

        for vecino, costo_viaje in grafo[estacion_actual].items():
            nuevo_costo = costo_real[estacion_actual] + costo_viaje
            if vecino not in costo_real or nuevo_costo < costo_real[vecino]:
                costo_real[vecino] = nuevo_costo
                costo_estimado_total = nuevo_costo + heuristica[vecino]
                heapq.heappush(rutas_por_evaluar, (costo_estimado_total, vecino))
                ruta_previa[vecino] = estacion_actual
    return None, 0

