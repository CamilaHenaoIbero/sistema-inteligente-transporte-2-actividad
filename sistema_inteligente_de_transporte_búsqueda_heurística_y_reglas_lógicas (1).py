def visualizar_ruta(grafo, ruta_optima, titulo):
    G = nx.Graph()

    # Agregar aristas y costos al grafo visual
    for nodo, vecinos in grafo.items():
        for vecino, costo in vecinos.items():
            G.add_edge(nodo, vecino, weight=costo)

    # Coordenadas fijas para que el mapa de estaciones se vea ordenado
    posiciones = {
        'A': (0, 2),
        'B': (2, 3),
        'C': (1, 0),
        'D': (3, 1),
        'E': (4, 3),
        'F': (5, 2)
    }

    plt.figure(figsize=(8, 5))

    # Dibujar todas las estaciones y conexiones base
    nx.draw_networkx_nodes(G, posiciones, node_size=700, node_color='lightblue')
    nx.draw_networkx_labels(G, posiciones, font_size=12, font_weight='bold')

    # Etiquetas de los costos en las líneas
    etiquetas_aristas = nx.get_edge_attributes(G, 'weight')
    nx.draw_networkx_edge_labels(G, posiciones, edge_labels=etiquetas_aristas)

    # Dibujar todas las conexiones grises
    nx.draw_networkx_edges(G, posiciones, edge_color='gray', width=2)

    # Si hay una ruta óptima, resaltarla en color VERDE y con líneas gruesas
    if ruta_optima:
        pares_ruta = list(zip(ruta_optima[:-1], ruta_optima[1:]))
        nx.draw_networkx_edges(G, posiciones, edgelist=pares_ruta, edge_color='green', width=4)
        nx.draw_networkx_nodes(G, posiciones, nodelist=ruta_optima, node_size=700, node_color='lightgreen')

    plt.title(titulo, fontsize=14, fontweight='bold')
    plt.axis('off')
    plt.show()


